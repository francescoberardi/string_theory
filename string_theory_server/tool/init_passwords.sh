#!/usr/bin/env bash
# Creates config/passwords.yaml for a fresh clone.
#
# Writes random `development` and `test` values for every secret the server
# (lib/server.dart) and the test config (config/test.yaml) need: database,
# serviceSecret, emailSecretHashPepper, jwtHmacSha512PrivateKey and
# jwtRefreshTokenHashPepper. Both run modes use an embedded PostgreSQL that
# Serverpod creates with this password, so no other setup is needed.
#
# Refuses to overwrite an existing file, and never prints the secrets.
# Needs openssl on the PATH.
#
# Usage: tool/init_passwords.sh [path]   (defaults to config/passwords.yaml)
set -euo pipefail

script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
target="${1:-$(dirname "$script_dir")/config/passwords.yaml}"

command -v openssl >/dev/null || {
  echo "error: openssl not found on PATH" >&2
  exit 1
}

if [ -e "$target" ]; then
  echo "error: $target already exists; not overwriting it" >&2
  exit 1
fi

# URL-safe random string of $1 bytes of entropy, without padding.
secret() { openssl rand -base64 "$1" | tr -d '\n=' | tr '+/' '-_'; }

section() {
  cat <<YAML
$1:
  database: '$(secret 24)'
  serviceSecret: '$(secret 24)'
  emailSecretHashPepper: '$(secret 24)'
  jwtHmacSha512PrivateKey: '$(secret 48)'
  jwtRefreshTokenHashPepper: '$(secret 24)'
YAML
}

mkdir -p "$(dirname "$target")"
umask 077
tmp="$(mktemp "$target.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# Generated by tool/init_passwords.sh. Keep this file out of version"
  echo "# control. Values are loaded into session.passwords per run mode."
  echo
  section development
  echo
  section test
} >"$tmp"
# `ln` fails if the target appeared meanwhile, so an existing file is never
# replaced.
ln "$tmp" "$target"

echo "Created $target with random development and test secrets."
